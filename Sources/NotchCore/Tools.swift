import Foundation

// The Tools module's models, without AppKit: clipboard history and the focus timer.

/// One copied text, or one copied image.
public struct ClipItem: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    /// The text; empty for an image.
    public var text: String
    public var copied: Date
    public var pinned: Bool
    /// The app it was copied in.
    public var source: String?
    /// A copied image as PNG (kept in memory only, like the text), its small preview for the
    /// list, and its size in pixels.
    public var image: Data?
    public var thumbnail: Data?
    public var pixelWidth: Int?
    public var pixelHeight: Int?

    public init(id: UUID = UUID(), text: String, copied: Date, pinned: Bool = false, source: String? = nil,
                image: Data? = nil, thumbnail: Data? = nil, pixelWidth: Int? = nil, pixelHeight: Int? = nil) {
        self.id = id
        self.text = text
        self.copied = copied
        self.pinned = pinned
        self.source = source
        self.image = image
        self.thumbnail = thumbnail
        self.pixelWidth = pixelWidth
        self.pixelHeight = pixelHeight
    }

    public var isImage: Bool { image != nil }
    /// Memory the image and its preview take.
    public var imageBytes: Int { (image?.count ?? 0) + (thumbnail?.count ?? 0) }

    /// One line for the list: whitespace folded, at most `limit` characters.
    public func line(_ limit: Int = 90) -> String {
        let folded = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return folded.count <= limit ? folded : String(folded.prefix(limit - 1)) + "…"
    }

    /// A copied web address on its own: its domain without "www." and the rest ("/path?query"),
    /// for a row that leads with the domain. Nil for any other text.
    public var link: (domain: String, rest: String)? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              let host = url.host, !host.isEmpty else { return nil }
        let domain = host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
        var rest = url.path == "/" ? "" : url.path
        if let query = url.query, !query.isEmpty { rest += "?" + query }
        return (domain, rest)
    }
}

/// What was copied, newest first, pinned items on top. Secrets never get in: copies marked
/// concealed or transient (password managers do) and copies made in a password app are skipped.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    public static let limit = 200
    /// Longer copies are kept up to this many characters.
    public static let maxLength = 20_000
    /// Images take memory: at most this many unpinned ones, each at most `maxImageBytes`.
    public static let imageLimit = 12
    public static let maxImageBytes = 15_000_000
    /// All images together, the pinned ones too, take at most this much memory: the oldest
    /// unpinned go first, and pins stop at `pinnedImageBudget`.
    public static let imageBudget = 150_000_000
    /// Pinned images stay below this, so a new copy always fits beside them.
    public static let pinnedImageBudget = imageBudget - maxImageBytes
    /// Checked before an image is decoded: the copied data (TIFF is uncompressed) and its pixels.
    public static let maxImageInputBytes = 160_000_000
    public static let maxImagePixels = 40_000_000

    /// Pasteboard types that mark a copy as secret or temporary (nspasteboard.org).
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Password apps: nothing copied in them is kept (the ignore list's fixed part).
    public static let skippedApps: Set<String> = Set(MemoryPrivacy.passwordApps.map(\.bundleID))

    public private(set) var items: [ClipItem] = []

    public init(items: [ClipItem] = []) { self.items = items }

    /// `ignored`: the apps on Tara's ignore list (`MemoryPrivacy.ignoredBundleIDs`), the password apps at least.
    public static func shouldSkip(types: [String], app bundleID: String?, ignored: Set<String> = skippedApps) -> Bool {
        types.contains { skippedTypes.contains($0) } || bundleID.map { ignored.union(skippedApps).contains($0) } == true
    }

    /// Adds a copy; the same text moves to the top instead of repeating. Blank text is ignored.
    /// Returns whether the list changed.
    @discardableResult
    public mutating func add(_ text: String, source: String? = nil, at date: Date) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return false }
        let kept = text.count > Self.maxLength ? String(text.prefix(Self.maxLength)) : text
        var pinned = false
        if let index = items.firstIndex(where: { $0.text == kept }) {
            pinned = items[index].pinned
            items.remove(at: index)
        }
        items.insert(ClipItem(text: kept, copied: date, pinned: pinned, source: source), at: 0)
        trim()
        return true
    }

    /// Adds a copied image (PNG); the same image moves to the top instead of repeating. Too large
    /// an image is not kept. Returns whether the list changed.
    @discardableResult
    public mutating func addImage(_ png: Data, thumbnail: Data?, width: Int, height: Int, source: String? = nil,
                                  at date: Date) -> Bool {
        guard !png.isEmpty, png.count <= Self.maxImageBytes else { return false }
        var pinned = false
        if let index = items.firstIndex(where: { $0.image == png }) {
            pinned = items[index].pinned
            items.remove(at: index)
        }
        items.insert(ClipItem(text: "", copied: date, pinned: pinned, source: source, image: png, thumbnail: thumbnail,
                              pixelWidth: width, pixelHeight: height), at: 0)
        trim()
        return true
    }

    /// Whether a copied image is small enough to decode, from its data's size and the pixel size
    /// its header gives.
    public static func acceptsImage(bytes: Int, width: Int, height: Int) -> Bool {
        bytes > 0 && bytes <= maxImageInputBytes && width > 0 && height > 0 && width * height <= maxImagePixels
    }

    /// Memory the images take (with their previews); `pinned`: only the pinned ones.
    public func imageBytes(pinned: Bool = false) -> Int {
        items.filter { $0.isImage && (!pinned || $0.pinned) }.reduce(0) { $0 + $1.imageBytes }
    }

    /// Pins or unpins; an image isn't pinned beyond `pinnedImageBudget`. Returns whether it changed.
    @discardableResult
    public mutating func togglePin(_ id: UUID) -> Bool {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return false }
        if !items[index].pinned, items[index].isImage,
           imageBytes(pinned: true) + items[index].imageBytes > Self.pinnedImageBudget { return false }
        items[index].pinned.toggle()
        return true
    }

    public mutating func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
    }

    /// Empties the history; pinned items stay.
    public mutating func clear() {
        items.removeAll { !$0.pinned }
    }

    /// Pinned first, then newest; with a query, the items containing it (case and accents ignored),
    /// also in the app it was copied in.
    public func list(matching query: String = "") -> [ClipItem] {
        let needle = query.trimmingCharacters(in: .whitespaces)
        let found = needle.isEmpty ? items : items.filter { item in
            [item.text, item.source ?? ""].contains { $0.range(of: needle, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
        return found.filter(\.pinned) + found.filter { !$0.pinned }
    }

    /// Drops the oldest unpinned items beyond the limit, and the oldest unpinned images beyond
    /// their count and the memory budget.
    private mutating func trim() {
        var unpinned = items.filter { !$0.pinned }.count
        while items.count > Self.limit, unpinned > 0, let last = items.lastIndex(where: { !$0.pinned }) {
            items.remove(at: last)
            unpinned -= 1
        }
        while items.filter({ $0.isImage && !$0.pinned }).count > Self.imageLimit,
              let last = items.lastIndex(where: { $0.isImage && !$0.pinned }) {
            items.remove(at: last)
        }
        while imageBytes() > Self.imageBudget, let last = items.lastIndex(where: { $0.isImage && !$0.pinned }) {
            items.remove(at: last)
        }
    }
}

/// Pomodoro: focus, a short break, and after every fourth focus a long one. The rounds chain on
/// their own until stopped; a pause holds the remaining time.
public struct FocusTimer: Equatable, Sendable {
    public enum Phase: String, Sendable {
        case idle, focus, shortBreak, longBreak

        public var title: String {
            switch self {
            case .idle: "Focus"
            case .focus: "Focus"
            case .shortBreak: "Break"
            case .longBreak: "Long break"
            }
        }
    }

    public var focusMinutes: Double = 25
    public var breakMinutes: Double = 5
    public var longBreakMinutes: Double = 15
    public var roundsBeforeLong = 4

    public private(set) var phase: Phase = .idle
    /// When the running phase ends; nil while idle or paused.
    public private(set) var endsAt: Date?
    /// Time left in a paused phase.
    public private(set) var pausedRemaining: TimeInterval?
    /// Focus rounds finished in this chain.
    public private(set) var round = 0
    /// Focus rounds finished today, and the day they count for.
    public private(set) var doneToday = 0
    public private(set) var day: DateComponents?

    public init() {}

    public var isRunning: Bool { endsAt != nil }
    public var isPaused: Bool { pausedRemaining != nil }

    public func length(of phase: Phase) -> TimeInterval {
        switch phase {
        case .idle, .focus: focusMinutes * 60
        case .shortBreak: breakMinutes * 60
        case .longBreak: longBreakMinutes * 60
        }
    }

    public func remaining(at now: Date) -> TimeInterval {
        if let endsAt { return max(0, endsAt.timeIntervalSince(now)) }
        return pausedRemaining ?? length(of: phase)
    }

    /// 0 at the start of the phase, 1 at its end.
    public func progress(at now: Date) -> Double {
        let total = length(of: phase)
        return total > 0 ? min(1, max(0, 1 - remaining(at: now) / total)) : 0
    }

    public mutating func start(at now: Date) {
        if isPaused { resume(at: now); return }
        guard phase == .idle else { return }
        begin(.focus, at: now)
    }

    public mutating func pause(at now: Date) {
        guard let endsAt else { return }
        pausedRemaining = max(0, endsAt.timeIntervalSince(now))
        self.endsAt = nil
    }

    public mutating func resume(at now: Date) {
        guard let left = pausedRemaining else { return }
        endsAt = now.addingTimeInterval(left)
        pausedRemaining = nil
    }

    /// Ends the chain.
    public mutating func stop() {
        phase = .idle
        endsAt = nil
        pausedRemaining = nil
        round = 0
    }

    /// Ends the current phase now and starts the next; returns the phase that ended.
    @discardableResult
    public mutating func skip(at now: Date) -> Phase {
        let ended = phase
        advance(at: now, finished: false)
        return ended
    }

    /// Call every second: when the phase is over, the next one starts. Returns the phase that just
    /// ended (for a sneak), else nil.
    public mutating func tick(at now: Date) -> Phase? {
        guard let endsAt, now >= endsAt else { return nil }
        let ended = phase
        advance(at: now, finished: true)
        return ended
    }

    private mutating func advance(at now: Date, finished: Bool) {
        switch phase {
        case .idle:
            begin(.focus, at: now)
        case .focus:
            if finished { countRound(at: now) }
            begin(round > 0 && round % roundsBeforeLong == 0 ? .longBreak : .shortBreak, at: now)
        case .shortBreak, .longBreak:
            begin(.focus, at: now)
        }
    }

    private mutating func countRound(at now: Date) {
        round += 1
        let today = Calendar.current.dateComponents([.year, .month, .day], from: now)
        if today != day {
            day = today
            doneToday = 0
        }
        doneToday += 1
    }

    private mutating func begin(_ next: Phase, at now: Date) {
        phase = next
        pausedRemaining = nil
        endsAt = now.addingTimeInterval(length(of: next))
    }
}

/// "24:59", "1:02:03".
public enum Countdown {
    public static func text(_ seconds: TimeInterval) -> String {
        let total = Int(seconds.rounded(.up))
        let hours = total / 3600, minutes = total / 60 % 60, rest = total % 60
        return hours > 0 ? String(format: "%d:%02d:%02d", hours, minutes, rest) : String(format: "%d:%02d", minutes, rest)
    }

    /// For the narrow ear beside the notch (about 24 pt): "45s", "12m", "1h59", "2h"; from ten
    /// hours on only the hours.
    public static func short(_ seconds: TimeInterval) -> String {
        let total = Int(seconds.rounded(.up))
        if total < 60 { return "\(total)s" }
        if total < 3600 { return "\(total / 60)m" }
        let hours = total / 3600, minutes = total / 60 % 60
        return minutes == 0 || hours >= 10 ? "\(hours)h" : String(format: "%dh%02d", hours, minutes)
    }
}

/// Battery levels of a Bluetooth device ("L 80 % · R 78 % · Case 52 %"), from
/// `system_profiler SPBluetoothDataType -json` (no Bluetooth permission needed).
public struct DeviceBattery: Equatable, Sendable {
    public var name: String
    public var left: Int?
    public var right: Int?
    public var caseLevel: Int?
    public var main: Int?

    public init(name: String, left: Int? = nil, right: Int? = nil, caseLevel: Int? = nil, main: Int? = nil) {
        self.name = name
        self.left = left
        self.right = right
        self.caseLevel = caseLevel
        self.main = main
    }

    /// The lowest earbud or the device's own level, for the icon.
    public var lowest: Int? { [left, right, main].compactMap { $0 }.min() }

    /// "L 80 % · R 78 % · Case 52 %", or "64 %".
    public var line: String {
        var parts: [String] = []
        if let left { parts.append("L \(left) %") }
        if let right { parts.append("R \(right) %") }
        if let main { parts.append("\(main) %") }
        if let caseLevel { parts.append("Case \(caseLevel) %") }
        return parts.joined(separator: " · ")
    }

    /// The audio output's name and the Bluetooth device's name belong together ("AirPods Pro" and
    /// "Max's AirPods Pro"); without an output name any device will do.
    public static func sameDevice(_ device: String, _ output: String?) -> Bool {
        guard let output, !output.isEmpty else { return true }
        let a = device.lowercased(), b = output.lowercased()
        return a == b || a.contains(b) || b.contains(a)
    }

    /// The connected device with a battery whose name matches `name` (the audio output's), else
    /// the first connected one with a battery.
    public static func parse(_ data: Data, preferring name: String?) -> DeviceBattery? {
        guard let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let controllers = root["SPBluetoothDataType"] as? [[String: Any]] else { return nil }
        func level(_ value: Any?) -> Int? {
            (value as? String).flatMap { Int($0.replacingOccurrences(of: "%", with: "").trimmingCharacters(in: .whitespaces)) }
        }
        var found: [DeviceBattery] = []
        for controller in controllers {
            for entry in controller["device_connected"] as? [[String: Any]] ?? [] {
                for (deviceName, value) in entry {
                    guard let info = value as? [String: Any] else { continue }
                    let battery = DeviceBattery(name: deviceName, left: level(info["device_batteryLevelLeft"]),
                                                right: level(info["device_batteryLevelRight"]),
                                                caseLevel: level(info["device_batteryLevelCase"]),
                                                main: level(info["device_batteryLevelMain"]))
                    if !battery.line.isEmpty { found.append(battery) }
                }
            }
        }
        return found.first { $0.name == name } ?? found.first { sameDevice($0.name, name) } ?? found.first
    }
}

/// A plain timer: counts down from a chosen time, or up like a stopwatch. Pausing keeps the time.
public struct SimpleTimer: Equatable, Sendable {
    public enum Mode: String, Sendable, CaseIterable { case countdown, stopwatch }

    public var mode: Mode = .countdown
    /// The countdown's length.
    public var duration: TimeInterval = 10 * 60
    public private(set) var startedAt: Date?
    /// Time run before the last start.
    public private(set) var accumulated: TimeInterval = 0

    public init() {}

    public var isRunning: Bool { startedAt != nil }
    /// Running, or paused with time on it.
    public var isActive: Bool { isRunning || accumulated > 0 }

    public func elapsed(at now: Date) -> TimeInterval {
        accumulated + (startedAt.map { max(0, now.timeIntervalSince($0)) } ?? 0)
    }

    public func remaining(at now: Date) -> TimeInterval { max(0, duration - elapsed(at: now)) }

    /// What the face shows: the time left (countdown) or the time gone (stopwatch).
    public func shown(at now: Date) -> TimeInterval { mode == .countdown ? remaining(at: now) : elapsed(at: now) }

    /// 0 to 1 through the countdown; the stopwatch goes round once a minute.
    public func progress(at now: Date) -> Double {
        mode == .countdown ? (duration > 0 ? min(1, elapsed(at: now) / duration) : 0)
            : elapsed(at: now).truncatingRemainder(dividingBy: 60) / 60
    }

    public mutating func start(at now: Date) {
        guard startedAt == nil else { return }
        startedAt = now
    }

    public mutating func pause(at now: Date) {
        guard startedAt != nil else { return }
        accumulated = elapsed(at: now)
        startedAt = nil
    }

    public mutating func reset() {
        startedAt = nil
        accumulated = 0
    }

    /// Call every second: true once when a countdown reaches zero (it resets).
    public mutating func tick(at now: Date) -> Bool {
        guard mode == .countdown, isRunning, remaining(at: now) <= 0 else { return false }
        reset()
        return true
    }
}
