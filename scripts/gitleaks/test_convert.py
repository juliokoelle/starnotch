"""Tests for convert.py, without the network or the Swift toolchain (the compile check is faked).

    python3 -m unittest discover -s scripts/gitleaks
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import convert  # noqa: E402

CONFIG = r"""
title = "a made-up gitleaks config"

[[rules]]
id = "demo-token"
description = "A demo token"
regex = '''\b(demo_[a-z0-9]{20})(?:[\x60'"\s;]|$)'''
entropy = 3.5
keywords = ["Demo_"]

[[rules]]
id = "demo-second-group"
regex = '''(?i)demo(login|token)[ =]+([a-z0-9]{16})'''
secretGroup = 2
keywords = ["demo"]

[[rules]]
id = "demo-named"
regex = '''\bDEMO(?:(?P<alg>abc)|(?P<key_ops>def))[a-z]{8,}'''
keywords = ["demo"]

[[rules]]
id = "demo-named-with-group"
regex = '''(?P<head>demo)-(x{4})'''
secretGroup = 2
keywords = ["demo-"]

[[rules]]
id = "demo-quotes"
regex = '''demo"#[a-z]+\#'''
keywords = ["demo"]

[[rules]]
id = "demo-file"
path = '''\.yaml$'''
regex = '''secret: (\w+)'''
keywords = ["secret"]

[[rules]]
id = "demo-file-only"
path = '''\.p12$'''

[[rules]]
id = "generic-api-key"
regex = '''(?i)key = (\w+)'''
keywords = ["key"]

[[rules]]
id = "demo-broken"
regex = '''demo(unclosed'''
keywords = ["demo"]
"""


def fake_check(patterns):
    """NSRegularExpression's answer, faked: an unclosed group or a Go-only named group fails."""
    return [p.count("(") == p.count(")") and "(?P<" not in p for p in patterns]


class ConvertTests(unittest.TestCase):
    def setUp(self):
        self.swift, self.left_out = convert.convert(CONFIG, "v0.0.0-demo", fake_check)

    def test_keeps_rules_with_id_keywords_regex_group_and_entropy(self):
        self.assertIn(r'''.init(id: "demo-token", keywords: ["demo_"], pattern: #"\b(demo_[a-z0-9]{20})(?:[\x60'"\s;]|$)"#, entropy: 3.5),''',
                      self.swift)
        self.assertIn('id: "demo-second-group"', self.swift)
        self.assertIn("group: 2", self.swift)

    def test_leaves_out_path_rules_the_generic_rule_and_what_does_not_compile(self):
        self.assertEqual(self.left_out, {
            "demo-file": "tied to a file path",
            "demo-file-only": "no regex",
            "generic-api-key": "the mask has its own labels and net",
            "demo-broken": "NSRegularExpression doesn't compile its regex",
        })
        for rid in self.left_out:
            self.assertNotIn(f'id: "{rid}"', self.swift)
            self.assertIn(f"//   {rid}: ", self.swift)

    def test_named_groups_capture_only_when_the_numbers_matter(self):
        self.assertIn(r'pattern: #"\bDEMO(?:(?:abc)|(?:def))[a-z]{8,}"#', self.swift)
        self.assertIn(r'pattern: #"(demo)\-(x{4})"#, group: 2', self.swift)

    def test_literal_hyphens_are_escaped_so_prefixes_do_not_read_like_keys(self):
        cases = {
            r"\b(sk-ant-demo01-[a-zA-Z0-9_\-]{93}AA)": r"\b(sk\-ant\-demo01\-[a-zA-Z0-9_\-]{93}AA)",
            r"(?i)a(?-i:[Aa]pi)": r"(?i)a(?-i:[Aa]pi)",
            r"(?i-s:a-b)": r"(?i-s:a\-b)",
            r"[[:alnum:]-]+-x": r"[[:alnum:]-]+\-x",
            r"[]-]-[^]-]": r"[]-]\-[^]-]",
            r"a\-b": r"a\-b",
        }
        for pattern, written in cases.items():
            self.assertEqual(convert.escape_hyphens(pattern), written)

    def test_raw_strings_get_a_delimiter_the_pattern_lacks(self):
        self.assertIn('pattern: ##"demo"#[a-z]+\\#"##', self.swift)

    def test_header_names_the_source_and_carries_the_mit_notice(self):
        self.assertTrue(self.swift.startswith("// Generated by scripts/gitleaks/convert.py"))
        self.assertIn("config/gitleaks.toml, v0.0.0-demo)", self.swift)
        self.assertIn("// MIT License", self.swift)
        self.assertIn("// Copyright (c) 2019 Zachary Rice", self.swift)
        self.assertIn("// The above copyright notice and this permission notice shall be included in all", self.swift)
        self.assertIn("// 5 rules. Left out:", self.swift)
        self.assertIn("extension ScreenMask {\n    static let gitleaksRules: [UpstreamRule] = [", self.swift)

    def test_the_same_config_gives_the_same_file(self):
        again, _ = convert.convert(CONFIG, "v0.0.0-demo", fake_check)
        self.assertEqual(self.swift, again)

    def test_no_regex_is_checked_when_nothing_is_kept(self):
        swift, left_out = convert.convert('[[rules]]\nid = "only-path"\npath = "x"\n', "v0", lambda _: self.fail("checked"))
        self.assertIn("// 0 rules. Left out:", swift)
        self.assertEqual(left_out, {"only-path": "no regex"})


if __name__ == "__main__":
    unittest.main()
